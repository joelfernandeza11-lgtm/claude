// Mapamundi estilizado (polígonos gruesos en lon/lat) para la pared de la oficina.

type Pt = [number, number]; // [lon, lat]

const LON0 = -170, LON1 = 180, LAT0 = 78, LAT1 = -58;

/** lon/lat -> fracción 0..1 dentro del mapa. */
export function project(lon: number, lat: number): { fx: number; fy: number } {
  return { fx: (lon - LON0) / (LON1 - LON0), fy: (LAT0 - lat) / (LAT0 - LAT1) };
}

