/** Convierte los polígonos a un path SVG en coordenadas 0..w x 0..h. */
export function landPath(w: number, h: number): string {
  return LAND.map((poly) =>
    poly
      .map(([lon, lat], i) => {
        const { fx, fy } = project(lon, lat);
        return `${i ? 'L' : 'M'}${(fx * w).toFixed(1)} ${(fy * h).toFixed(1)}`;
      })
      .join('') + 'Z',
  ).join('');
}

